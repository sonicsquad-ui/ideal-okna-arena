function runNewsAggregation(db) {
  let addedCount = 0;
  const now = new Date();
  
  // Format current date/time for publication
  const pubDateStr = now.toISOString().replace('T', ' ').substring(0, 19);

  for (const item of FRESH_NEWS_TEMPLATES) {
    const slug = transliterate(item.title);
    
    // Check if news already exists by slug
    const existing = db.prepare('SELECT id FROM news WHERE slug = ?').get(slug);
    if (!existing) {
      const metaTitle = `${item.title} — Чемпион-Теннис`;
      const metaDesc = item.excerpt.slice(0, 155) + '...';
      
      db.prepare(`
        INSERT INTO news (
          category, slug, title, excerpt, content, image,
          source_name, source_url, author, views, published_at,
          is_featured, is_hot_24h, meta_title, meta_description
        ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
      `).run(
        item.category,
        slug,
        item.title,
        item.excerpt,
        item.content.trim(),
        item.image,
        item.source_name,
        item.source_url,
        'Редакция Champion-Tennis.ru',
        Math.floor(Math.random() * 450) + 120,
        pubDateStr,
        item.category === 'atp' || item.category === 'wta' ? 1 : 0,
        1,
        metaTitle,
        metaDesc
      );
      addedCount++;
    }
  }

  // Update last aggregation timestamp in global_blocks
  const updateInfo = {
    last_run: now.toISOString(),
    last_run_msk: now.toLocaleTimeString('ru-RU', { timeZone: 'Europe/Moscow' }) + ' ' + now.toLocaleDateString('ru-RU', { timeZone: 'Europe/Moscow' }),
    added_count: addedCount,
    status: 'success'
  };
  
  db.prepare(`
    INSERT INTO global_blocks (key, value_json)
    VALUES ('news_cron_status', ?)
    ON CONFLICT(key) DO UPDATE SET value_json = excluded.value_json
  `).run(JSON.stringify(updateInfo));

  return updateInfo;
}

module.exports = { runNewsAggregation, FRESH_NEWS_TEMPLATES };
